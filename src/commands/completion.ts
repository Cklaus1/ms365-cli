import { Argument, Command } from 'commander';
import { handleErrors } from '../errors.js';

const SHELLS = ['bash', 'zsh', 'fish', 'powershell'] as const;
type Shell = typeof SHELLS[number];

/**
 * Lookup tables for one command tree, keyed by the command path ("" is the root, "mail list" a
 * leaf). Every generated script embeds these, so completion never calls back into ms365.
 */
interface Tables {
  /** "parent|word" → child path; aliases map to their command's path. */
  child: Map<string, string>;
  /** Subcommand names of a path. */
  subs: Map<string, string[]>;
  /** Flags offered for a path (root flags, --help among them, are global and offered everywhere). */
  opts: Map<string, string[]>;
  /** Flags offered only when nothing but `ms365` is typed (--version); keyed "" alone. */
  rootopts: Map<string, string[]>;
  /** "path|flag" → the flag's value choices, or ["*"] for a free-form value. */
  optarg: Map<string, string[]>;
  /** Choices for the first positional argument of a leaf. */
  posargs: Map<string, string[]>;
}

function buildTables(program: Command): Tables {
  const t: Tables = { child: new Map(), subs: new Map(), opts: new Map(), rootopts: new Map(), optarg: new Map(), posargs: new Map() };
  const versionName = (program as unknown as { _versionOptionName?: string })._versionOptionName;
  const walk = (cmd: Command, path: string): void => {
    const flags = path ? [] : ['--help'];
    for (const o of cmd.options) {
      if (o.hidden) continue;
      if (!path && versionName && o.attributeName() === versionName) {
        t.rootopts.set('', [o.long ?? o.short!]);
        continue;
      }
      flags.push(o.long ?? o.short!);
      if (o.required || o.optional) {
        const value = o.argChoices ? [...o.argChoices] : ['*'];
        for (const f of [o.long, o.short]) if (f) t.optarg.set(`${path}|${f}`, value);
      }
    }
    t.opts.set(path, flags);
    const subs = cmd.commands.filter(c => !(c as unknown as { _hidden?: boolean })._hidden);
    if (subs.length) {
      t.subs.set(path, subs.map(c => c.name()));
      for (const sub of subs) {
        const subPath = path ? `${path} ${sub.name()}` : sub.name();
        for (const name of [sub.name(), ...sub.aliases()]) t.child.set(`${path}|${name}`, subPath);
        walk(sub, subPath);
      }
    } else {
      const choices = cmd.registeredArguments[0]?.argChoices;
      if (choices) t.posargs.set(path, [...choices]);
    }
  };
  walk(program, '');
  return t;
}

const TABLE_NAMES = ['child', 'subs', 'opts', 'rootopts', 'optarg_key', 'posargs'] as const;
const tableOf = (t: Tables, name: typeof TABLE_NAMES[number]): Map<string, string | string[]> =>
  name === 'optarg_key' ? t.optarg : t[name];

// ── bash / zsh: the same POSIX-style lookup functions, different drivers ──

const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

function posixTables(t: Tables): string {
  return TABLE_NAMES.map(name => {
    const cases = [...tableOf(t, name)].map(([k, v]) => `    ${sq(k)}) REPLY=${sq(Array.isArray(v) ? v.join(' ') : v)} ;;`);
    return [`_ms365_${name}() {`, '  case "$1" in', ...cases, "    *) REPLY='' ;;", '  esac', '}'].join('\n');
  }).join('\n\n');
}

/** Shared walk: sets cmdpath (deepest command typed) and pending (choices of a flag awaiting its value). */
const POSIX_WALK = (words: string, from: number, to: string) => `
  for ((i = ${from}; i < ${to}; i++)); do
    w=\${${words}[i]}
    [[ $w == '=' ]] && continue
    if [[ -n $pending ]]; then pending=''; continue; fi
    if [[ $w == -* ]]; then
      [[ $w == *=* ]] || { _ms365_optarg "$cmdpath" "$w"; pending=$REPLY; }
      continue
    fi
    _ms365_child "$cmdpath|$w"
    [[ -n $REPLY ]] && cmdpath=$REPLY
  done`;

const POSIX_OPTARG = `_ms365_optarg() {
  _ms365_optarg_key "$1|$2"
  [[ -n $REPLY ]] || _ms365_optarg_key "|$2"
}`;

function bashScript(t: Tables): string {
  return `# ms365 bash completion (generated by \`ms365 completion bash\`)
${posixTables(t)}

${POSIX_OPTARG}

_ms365() {
  local cur=\${COMP_WORDS[COMP_CWORD]} cmdpath='' pending='' w i REPLY opts
  COMPREPLY=()${POSIX_WALK('COMP_WORDS', 1, 'COMP_CWORD')}
  if [[ -n $pending ]]; then
    [[ $cur == '=' ]] && cur=''
    [[ $pending == '*' ]] || COMPREPLY=($(compgen -W "$pending" -- "$cur"))
    return
  fi
  if [[ $cur == --*=* ]]; then
    _ms365_optarg "$cmdpath" "\${cur%%=*}"
    [[ -z $REPLY || $REPLY == '*' ]] || COMPREPLY=($(compgen -P "\${cur%%=*}=" -W "$REPLY" -- "\${cur#*=}"))
    return
  fi
  if [[ $cur == -* ]]; then
    _ms365_opts "$cmdpath"; opts=$REPLY
    _ms365_rootopts "$cmdpath"; opts="$opts $REPLY"
    REPLY=''; [[ -z $cmdpath ]] || _ms365_opts ''
    COMPREPLY=($(compgen -W "$opts $REPLY" -- "$cur"))
    return
  fi
  _ms365_subs "$cmdpath"
  [[ -n $REPLY ]] || _ms365_posargs "$cmdpath"
  [[ -n $REPLY ]] && COMPREPLY=($(compgen -W "$REPLY" -- "$cur"))
}

complete -o default -F _ms365 ms365
`;
}

function zshScript(t: Tables): string {
  return `#compdef ms365
# ms365 zsh completion (generated by \`ms365 completion zsh\`)
${posixTables(t)}

${POSIX_OPTARG}

_ms365() {
  local cur=\${words[CURRENT]} cmdpath='' pending='' w i REPLY opts${POSIX_WALK('words', 2, 'CURRENT')}
  if [[ -n $pending ]]; then
    if [[ $pending == '*' ]]; then _files; else compadd -- \${=pending}; fi
    return
  fi
  if [[ $cur == --*=* ]]; then
    local flag=\${cur%%=*}
    _ms365_optarg "$cmdpath" "$flag"
    if [[ $REPLY == '*' ]]; then compset -P '*='; _files
    elif [[ -n $REPLY ]]; then compadd -- \${\${=REPLY}/#/$flag=}; fi
    return
  fi
  if [[ $cur == -* ]]; then
    _ms365_opts "$cmdpath"; opts=$REPLY
    _ms365_rootopts "$cmdpath"; opts="$opts $REPLY"
    REPLY=''; [[ -z $cmdpath ]] || _ms365_opts ''
    compadd -- \${=opts} \${=REPLY}
    return
  fi
  _ms365_subs "$cmdpath"
  [[ -n $REPLY ]] || _ms365_posargs "$cmdpath"
  if [[ -n $REPLY ]]; then compadd -- \${=REPLY}; else _files; fi
}

if [[ \${zsh_eval_context[-1]} == loadautofunc ]]; then
  _ms365 "$@"
else
  compdef _ms365 ms365
fi
`;
}

// ── fish ──

const fq = (s: string) => `'${s.replace(/[\\']/g, '\\$&')}'`;

function fishScript(t: Tables): string {
  const tables = TABLE_NAMES.map(name => {
    const cases = [...tableOf(t, name)].map(([k, v]) =>
      `        case ${fq(k)}\n            printf '%s\\n' ${(Array.isArray(v) ? v : [v]).map(fq).join(' ')}`);
    return [`function __ms365_${name}`, '    switch $argv[1]', ...cases, '    end', 'end'].join('\n');
  }).join('\n\n');
  return `# ms365 fish completion (generated by \`ms365 completion fish\`)
${tables}

function __ms365_optarg
    set -l v (__ms365_optarg_key "$argv[1]|$argv[2]")
    test -n "$v"; or set v (__ms365_optarg_key "|$argv[2]")
    printf '%s\\n' $v
end

function __ms365_complete
    set -l tokens (commandline -opc)
    set -e tokens[1]
    set -l cur (commandline -ct)
    set -l cmdpath ''
    set -l pending
    for w in $tokens
        if test -n "$pending"
            set pending
            continue
        end
        if string match -q -- '-*' $w
            string match -q -- '*=*' $w; or set pending (__ms365_optarg "$cmdpath" $w)
            continue
        end
        set -l next (__ms365_child "$cmdpath|$w")
        test -n "$next"; and set cmdpath $next
    end
    if test -n "$pending"
        if test "$pending" = '*'
            __fish_complete_path $cur
        else
            printf '%s\\n' $pending
        end
        return
    end
    if string match -q -- '--*=*' $cur
        set -l flag (string split -m 1 = -- $cur)[1]
        set -l values (__ms365_optarg "$cmdpath" $flag)
        if test "$values" = '*'
            printf '%s\n' "$flag="(__fish_complete_path (string split -m 1 = -- $cur)[2])
        else if test -n "$values"
            printf '%s\n' "$flag="$values
        end
        return
    end
    if string match -q -- '-*' $cur
        __ms365_opts "$cmdpath"
        __ms365_rootopts "$cmdpath"
        test -z "$cmdpath"; or __ms365_opts ''
        return
    end
    set -l words (__ms365_subs "$cmdpath")
    test -n "$words"; or set words (__ms365_posargs "$cmdpath")
    if test -n "$words"
        printf '%s\\n' $words
    else
        __fish_complete_path $cur
    end
end

complete -c ms365 -e
complete -c ms365 -f -a '(__ms365_complete)'
`;
}

// ── PowerShell ──

const pq = (s: string) => `'${s.replace(/'/g, "''")}'`;

function powershellScript(t: Tables): string {
  const tables = TABLE_NAMES.map(name => {
    const v = name === 'optarg_key' ? 'optarg' : name;
    const rows = [...tableOf(t, name)].map(([k, val]) =>
      `    $${v}[${pq(k)}] = ${Array.isArray(val) ? `@(${val.map(pq).join(', ')})` : pq(val)}`);
    return [`    $${v} = [hashtable]::new([StringComparer]::Ordinal)`, ...rows].join('\n');
  }).join('\n');
  return `# ms365 PowerShell completion (generated by \`ms365 completion powershell\`)
Register-ArgumentCompleter -Native -CommandName ms365 -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
${tables}
    $words = @($commandAst.CommandElements | Where-Object { $_.Extent.EndOffset -lt $cursorPosition } | ForEach-Object { $_.Extent.Text } | Select-Object -Skip 1)
    $cmdpath = ''
    $pending = $null
    foreach ($w in $words) {
        if ($pending) { $pending = $null; continue }
        if ($w.StartsWith('-')) {
            if (-not $w.Contains('=')) {
                $pending = $optarg["$cmdpath|$w"]
                if (-not $pending) { $pending = $optarg["|$w"] }
            }
            continue
        }
        $next = $child["$cmdpath|$w"]
        if ($next) { $cmdpath = $next }
    }
    if ($pending) {
        if ($pending -contains '*') { return }
        $candidates = $pending
    } elseif ($wordToComplete -match '^(--[^=]+)=') {
        $flag = $Matches[1]
        $values = $optarg["$cmdpath|$flag"]
        if (-not $values) { $values = $optarg["|$flag"] }
        if (-not $values -or $values -contains '*') { return }
        $candidates = $values | ForEach-Object { "$flag=$_" }
    } elseif ($wordToComplete.StartsWith('-')) {
        $candidates = @($opts[$cmdpath]) + @($rootopts[$cmdpath]) + @(if ($cmdpath) { $opts[''] })
    } elseif ($subs[$cmdpath]) {
        $candidates = $subs[$cmdpath]
    } elseif ($posargs[$cmdpath]) {
        $candidates = $posargs[$cmdpath]
    } else {
        return
    }
    $candidates | Where-Object { $_ -like "$wordToComplete*" } | Select-Object -Unique | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
`;
}

const GENERATORS: Record<Shell, (t: Tables) => string> = {
  bash: bashScript,
  zsh: zshScript,
  fish: fishScript,
  powershell: powershellScript,
};

/** The completion script for one shell, generated from the live command tree. */
export function completionScript(program: Command, shell: Shell): string {
  return GENERATORS[shell](buildTables(program));
}

const INSTALL = `
Install (re-run after upgrading ms365):
  bash        ms365 completion bash > ~/.local/share/bash-completion/completions/ms365
              (or add  source <(ms365 completion bash)  to ~/.bashrc)
  zsh         ms365 completion zsh > "\${fpath[1]}/_ms365"   then restart zsh
              (or add  source <(ms365 completion zsh)  to ~/.zshrc after compinit)
  fish        ms365 completion fish > ~/.config/fish/completions/ms365.fish
  powershell  ms365 completion powershell | Out-String | Invoke-Expression
              (add that line to $PROFILE to keep it)

The script is static: tab completion never runs ms365.`;

export function registerCompletionCommand(program: Command): void {
  program
    .command('completion')
    .description('Print a shell completion script (bash, zsh, fish, powershell)')
    .addArgument(new Argument('<shell>', 'Shell to generate for').choices([...SHELLS]))
    .addHelpText('after', INSTALL)
    .action(handleErrors(async (shell: Shell) => {
      process.stdout.write(completionScript(program, shell));
    }));
}
